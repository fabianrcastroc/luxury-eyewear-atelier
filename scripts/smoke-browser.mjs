import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000');
await page.locator('.product').first().waitFor();
assert.equal(await page.locator('.product').count(),6);
await page.screenshot({path:'/tmp/miscante-desktop.png',fullPage:true});
await page.screenshot({path:'.github/miscante-preview.png'});
await page.locator('[data-category="optica"]').click();
assert.equal(await page.locator('.product').count(),2);
await page.locator('[data-category="all"]').click();
await page.locator('[data-favorite="solar"]').click();
await page.locator('[data-category="favoritos"]').click();
assert.equal(await page.locator('.product').count(),1);
await page.locator('[data-category="all"]').click();
await page.locator('#search-toggle').click();
await page.locator('#search').fill('champagne');
assert.equal(await page.locator('.product').count(),1);
await page.locator('#clear-search').click();
await page.locator('.product-heading [data-product="solar"]').click();
await page.locator('#product-dialog [data-add]').click();
await page.locator('#product-dialog [data-close]').click();
await page.reload();
assert.equal(await page.locator('#cart-count').textContent(),'1');
await page.locator('#cart-toggle').click();
assert.match(await page.locator('.total').textContent(),/164.000/);
await page.locator('[data-delta="1"]').click();
assert.match(await page.locator('.total').textContent(),/318.000/);
await page.locator('#checkout').click();
await page.locator('input[name="name"]').fill('Visitante de prueba');
await page.locator('input[name="email"]').fill('demo@example.com');
await page.locator('input[name="address"]').fill('Dirección de prueba 123');
await page.locator('input[name="city"]').fill('Santiago');
await page.locator('#checkout-form input[type="checkbox"]').check();
await page.locator('#checkout-form button[type="submit"],#checkout-form button:not([type])').click();
await page.getByText('PEDIDO DE PRUEBA COMPLETADO',{exact:true}).waitFor();
assert.equal(await page.locator('#cart-count').textContent(),'0');
await page.locator('#cart-dialog [data-close]').first().click();
await page.locator('#newsletter-email').fill('demo@example.com');
await page.locator('#newsletter-form button').click();
assert.equal(await page.evaluate(()=>localStorage.getItem('miscante-newsletter')),'true');
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:3000');
await page.locator('.product').first().waitFor();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'/tmp/miscante-mobile.png',fullPage:true});
await page.locator('.product-heading [data-product="noir"]').click();
assert.equal(await page.locator('#product-dialog').evaluate(e=>e.scrollWidth<=e.clientWidth),true);
await page.locator('#product-dialog [data-add]').click();
await page.keyboard.press('Escape');
await page.locator('#cart-toggle').click();
await page.locator('[data-remove="noir"]').click();
assert.equal(await page.locator('#cart-count').textContent(),'0');
assert.deepEqual(errors,[]);
console.log('PASS: catálogo, filtros, búsqueda, favoritos, persistencia, producto, cantidades, envío, checkout, newsletter, móvil y consola.');
await browser.close();
