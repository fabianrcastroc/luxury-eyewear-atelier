import {cp,mkdir,readFile,writeFile,rm} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.dirname(here),stage=path.join(root,'.desktop-build');
await rm(stage,{recursive:true,force:true});await mkdir(path.join(stage,'desktop','resources'),{recursive:true});
await cp(path.join(root,'dist','fr'),path.join(stage,'dist'),{recursive:true});
for(const file of ['main.cjs','electron-builder.yml','smoke-offline.mjs'])await cp(path.join(here,file),path.join(stage,'desktop',file));
for(const file of ['package.json','package-lock.json'])await cp(path.join(here,file),path.join(stage,file));
const sharp=(await import('sharp')).default;
const png=await sharp(path.join(root,'software-fr','favicon.svg')).resize(256,256).png().toBuffer();
const header=Buffer.alloc(22);header.writeUInt16LE(1,2);header.writeUInt16LE(1,4);header.writeUInt16LE(1,10);header.writeUInt16LE(32,12);header.writeUInt32LE(png.length,14);header.writeUInt32LE(22,18);
await writeFile(path.join(stage,'desktop','resources','icon.png'),png);
await writeFile(path.join(stage,'desktop','resources','icon.ico'),Buffer.concat([header,png]));
let config=await readFile(path.join(stage,'desktop','electron-builder.yml'),'utf8');config=config.replace('win:\n','win:\n  icon: desktop/resources/icon.ico\n');await writeFile(path.join(stage,'desktop','electron-builder.yml'),config);
console.log(stage);
